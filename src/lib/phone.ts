/**
 * تحقّق رقم الجوال — نظير phoneInput في server/src/lib/schemas.ts.
 *
 * النمط واحد في الطرفين عمداً: النموذج يمنع الإرسال، والخادم يمنع
 * الكتابة. تكرارٌ مقصود لا ازدواج — الواجهة تُبنى مرّة وتُخدَّم من
 * المتصفح، فلا يجوز أن تكون هي الحارس الوحيد على ما يدخل القاعدة.
 * وإن تغيّر النمط يوماً فالملفّان معاً يُعدَّلان.
 */
export const PHONE_PATTERN = /^09\d{8}$/;

/**
 * هل تصلح القيمة للإرسال؟
 *
 * الحقل اختياري، فالفراغ صالح: `true` تعني «لا يمنع الحفظ» لا «رقم
 * صحيح». ولذلك لا تُستعمل للسؤال عن وجود رقم — استعمل القيمة نفسها.
 */
export function phoneAcceptable(value: string): boolean {
  const trimmed = value.trim();
  return trimmed === "" || PHONE_PATTERN.test(trimmed);
}
