/**
 * الأسباب الجاهزة لإضافة النقاط وخصمها — مصدر واحد للنافذتين.
 *
 * ── لماذا مفاتيح لا نصوصاً؟ ─────────────────────────────────────────
 * كانت الأسباب نصوصاً عربية ثابتة داخل QuickPointsModal، لأن استدعاء
 * t مع returnObjects على مصفوفة في ملف الترجمة كان يعيد المفتاح نصّاً
 * فلا تظهر الرقاقات إطلاقاً. والحلّ المتّبع هنا يتفادى ذلك من أصله:
 * المصفوفة مفاتيحُ مفردة، وكل مفتاح يُترجَم باستدعاء t عادي — فلا
 * returnObjects ولا عودة إلى نصّ عربي محشور في الشيفرة.
 *
 * ── ولماذا ملف مشترك؟ ───────────────────────────────────────────────
 * نافذة النقاط السريعة ونافذة إضافة النقاط تعرضان الأسباب نفسها. وقد
 * كانتا مصدرين منفصلين فانحرفا فعلاً: «إتقان التسميع» بقيت في ملف
 * الترجمة بعد أن صارت «مكافأة بالدرس الجماعي» في الشيفرة. ومصدرٌ واحد
 * يمنع تكرار ذلك.
 */

export type PointsOperation = "add" | "deduct";

/**
 * مفاتيح الأسباب لكل عملية — تُترجَم تحت `pointsReasons.*` في locales.
 *
 * الترتيب مقصود: الأكثر استعمالاً أولاً، فالرقاقة الأولى هي المقصودة
 * غالباً.
 */
export const REASON_PRESET_KEYS: Record<PointsOperation, string[]> = {
  add: ["lessonReward", "groupLessonReward", "goodManners"],
  deduct: [
    "leftLesson",
    "disruption",
    "tooMuchTalking",
    "insultedTeacher",
    "insultedSupervisor",
  ],
};

/**
 * الأسباب الجاهزة مترجَمةً بلغة الواجهة الحالية.
 *
 * @param t دالة الترجمة من useTranslation.
 *
 * ملاحظة: النصّ المعروض هو نفسه النصّ الذي يُحفظ في سجلّ النقاط، فسبب
 * يُختار والواجهة إنجليزية يُحفظ إنجليزياً. وهذا مقصود: المحفوظ يطابق
 * ما رآه من سجّله، والبديل (حفظُ نصٍّ غير الذي ضغطه) أسوأ.
 */
export function reasonPresets(
  t: (key: string) => string,
  operation: PointsOperation
): string[] {
  return REASON_PRESET_KEYS[operation].map((key) => t(`pointsReasons.${key}`));
}
