-- تحقّق سريع بعد التنفيذ
SELECT 'المستخدمون' AS الجدول, COUNT(*) AS العدد FROM users
UNION ALL SELECT 'الحلقات',   COUNT(*) FROM halaqat
UNION ALL SELECT 'الطلاب',    COUNT(*) FROM students
UNION ALL SELECT 'التلاوات',  COUNT(*) FROM recitations
UNION ALL SELECT 'حركات النقاط', COUNT(*) FROM point_transactions;

-- يجب ألا يُعيد هذا أي صف: رصيد كل طالب = مجموع حركاته
SELECT s.id, s.name, s.points AS الرصيد_المخزَّن, COALESCE(SUM(p.delta), 0) AS مجموع_الحركات
FROM students s LEFT JOIN point_transactions p ON p.student_id = s.id
GROUP BY s.id HAVING s.points <> COALESCE(SUM(p.delta), 0);
