-- 013 | دمج مرحلتَي الإعدادي والثانوي في مرحلة واحدة
--
-- المرحلة (007) كانت primary | preparatory | secondary، والمعهد ينقسم
-- فعلياً إلى ثلاثة أقسام: ابتدائي، إعدادي وثانوي (قسم واحد)، مكثفة.
-- فبقاء المرحلة على تقسيم رباعيّ لا وجود له كان يعرض في نموذج الحلقة
-- خيارات لا تقابل شيئاً في المعهد — والحقلان متجاوران في النموذج.
--
-- القيم الجديدة: primary | middle_high | intensive، مطابقة لأقسام
-- المعهد (DEPARTMENTS) واحدةً بواحدة، مع بقاء الحقلين منفصلين: المرحلة
-- وصفٌ للحلقة، والقسم يقرّر من يراها.
--
-- ── لماذا الدمج لا التعيين؟ ─────────────────────────────────────────
-- preparatory و secondary كلاهما يقع في القسم المدمج، فتحويلهما إلى
-- middle_high لا يفقد معلومة إلا التفريق بينهما داخل القسم — وهو تفريق
-- لم يكن يُستعمل في أي استعلام أو تقرير (grep على stage: العرض وحده).
--
-- الحلقات المكثّفة القائمة لا سبيل إلى استنتاجها من المرحلة القديمة:
-- المكثفة لم يكن لها مقابل أصلاً. تُصحَّح يدوياً من 'إدارة الحلقات' لمن
-- أرادها، وحتى ذلك الحين تبقى على مرحلتها القديمة المحوَّلة.
--
-- العمود بلا CHECK كما في 007 — التحقق مطبَّق بـ zod في طبقة الـ API.
-- =====================================================================

UPDATE halaqat
SET    stage = 'middle_high'
WHERE  stage IN ('preparatory', 'secondary');
