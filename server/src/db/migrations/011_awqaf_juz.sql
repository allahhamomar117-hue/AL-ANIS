-- 011 | الجزء المُختبَر في سبر الأوقاف
--
-- الدورة تُعرَّف بشهرها وبالجزء الذي يُسبَر فيه (1..30)، وكان الحقل
-- الحرّ notes يحمل هذه المعلومة نصّاً غير منضبط ("جزء عمّ"، "٣٠") فلا
-- يصلح للفرز ولا للإحصاء.
--
-- العمود يقبل NULL رغم أنه مطلوب في الواجهة والمسار: الصفوف القديمة لا
-- جزء لها ولا سبيل إلى استنتاجه، وجعله NOT NULL يفرض قيمة كاذبة عليها.
-- الإلزام مفروض عند الإنشاء في POST /api/awqaf.
--
-- notes يبقى في الجدول ولا يُحذف: بيانات مكتوبة سلفاً لا تُتلَف بترقية،
-- وقد ارتفع عن الواجهة وحدها.
-- =====================================================================

ALTER TABLE awqaf_records
  ADD COLUMN juz INTEGER CHECK (juz IS NULL OR juz BETWEEN 1 AND 30);
