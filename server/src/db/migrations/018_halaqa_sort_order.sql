-- 018 | ترتيب الحلقات يدوياً
--
-- ترتيب الحلقات كان يُشتقّ من الاسم وحده (compareNatural في lib/sort.ts)،
-- وهو ترتيبٌ صحيح ما دامت الأسماء أرقاماً متتابعة. لكنّ المدير يرتّب
-- بمعايير لا يحملها الاسم: حلقةٌ يقدّمها لأنها الأكبر، وأخرى يؤخّرها
-- لأنها جديدة. فالترتيب يصير بياناً يُحفظ لا اشتقاقاً يُحسب.
--
-- ── لماذا DEFAULT 0 لا ترقيمٌ أوّليّ؟ ────────────────────────────────
-- 0 تعني «لم يُرتَّب بعد»، والاستعلام يفرز (sort_order, ثم الاسم طبيعياً)
-- — فقاعدةٌ لم يُلمس ترتيبها تبقى على ترتيبها الحالي حرفياً، ولا يتغيّر
-- شيء تحت يد المستخدم يوم الترقية. وأوّل سحبٍ يُنزل أرقاماً من 1 فتتقدّم
-- المرتَّبة، وهو ما طلبه المدير صراحةً حين سحب.
--
-- ولا يصحّ الترقيم الأوّليّ هنا على أي حال: الترتيب المطلوب طبيعيّ
-- (numeric collation) ولا سبيل إليه في SQL — ولهذا خرج إلى JS أصلاً.
-- =====================================================================

ALTER TABLE halaqat ADD COLUMN sort_order INTEGER NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS idx_halaqat_sort_order ON halaqat (sort_order);
