-- 012 | أقسام المعهد
--
-- المعهد ينقسم إلى ثلاثة أقسام: PRIMARY (ابتدائي)، MIDDLE_HIGH (إعدادي
-- وثانوي)، INTENSIVE (مكثفة). كل حلقة تتبع قسماً واحداً، وكل إداري
-- (مدير أو مشرف) إمّا أن يُقصر على قسم أو يُترك عاماً.
--
-- ── لماذا لا دور SUPER_ADMIN؟ ────────────────────────────────────────
-- الدور يجيب عن "ماذا يفعل"، والقسم يجيب عن "على من". خلطهما في عمود
-- واحد يضاعف الأدوار كلما زاد قسم. فبقيت الأدوار ثلاثة كما هي، ودلالة
-- users.department هي:
--   NULL  ⇒ نطاق المعهد كامل (المدير العام).
--   قيمة  ⇒ نطاق القسم وحده (مدير القسم).
-- والمدرّس لا يعنيه العمود: نطاقه حلقاته المسندة كما كان.
--
-- ── لماذا NULL مسموح في halaqat.department؟ ─────────────────────────
-- الحلقات القائمة قبل هذه الترقية لا قسم لها ولا سبيل إلى استنتاجه —
-- stage (primary|preparatory|secondary) وصفٌ دراسي لا تقسيم إداري،
-- والمكثفة لا تقابله أصلاً. جعله NOT NULL يفرض قيمة كاذبة على كل صفّ.
-- الإلزام مفروض في طبقة الـ API عند الإنشاء.
--
-- ⚠ الحلقة بلا قسم لا يراها إلا المدير العام. هذا مقصود: البديل أن
--   تظهر لكل الأقسام فتتسرّب البيانات. أسنِد الحلقات القائمة إلى أقسامها
--   من 'إدارة الحلقات' بعد الترقية.
--
-- العمودان بلا CHECK: ALTER TABLE في SQLite لا يعيد بناء الجدول، ونمط
-- 007 نفسه — التحقق مطبَّق بـ zod في طبقة الـ API.
-- =====================================================================

ALTER TABLE users   ADD COLUMN department TEXT;
ALTER TABLE halaqat ADD COLUMN department TEXT;

CREATE INDEX IF NOT EXISTS idx_halaqat_department ON halaqat (department);
