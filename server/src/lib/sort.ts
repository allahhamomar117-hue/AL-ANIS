/**
 * ترتيب الأسماء المرقَّمة ترتيباً طبيعياً.
 *
 * أسماء الحلقات تبدأ بأرقامها ("1 . 2"، "3 ."، "10 .")، وترتيبُ النصّ
 * المعجميّ يضع "10" قبل "3" لأنه يقارن المحارف لا الأعداد. والأسوأ أن
 * النتيجة تختلف بين المحرّكين: ترتيب SQLite بايتيّ، وترتيب Postgres يتبع
 * لغة القاعدة فيتجاهل الفراغات والنقاط — فيبدو الترتيب على الواجهة
 * عشوائياً لا مقلوباً وحسب.
 *
 * فالترتيب يُنقل إلى هنا: قائمة الحلقات عشراتُ صفوف لا آلاف، وفرزُها بعد
 * الجلب أرخص من فرضِ ترتيبٍ موحَّد على لهجتَي SQL.
 *
 * numeric: true هو بيت القصيد — يقارن سلاسل الأرقام داخل النصّ كأعداد.
 * و"ar" لأن بقية الاسم عربي، وsensitivity: "base" حتى لا تفرّق التشكيلات
 * والهمزات بين اسمين يقرؤهما المستخدم واحداً.
 */
const collator = new Intl.Collator("ar", { numeric: true, sensitivity: "base" });

/** مقارنة نصّين ترتيباً طبيعياً — تُمرَّر مباشرةً إلى Array.prototype.sort. */
export function compareNatural(a: string, b: string): number {
  return collator.compare(a, b);
}

/** فرز صفوف حسب حقل نصّي واحد، ترتيباً طبيعياً. نسخة جديدة لا فرز بالمكان. */
export function sortByNatural<T>(rows: T[], key: (row: T) => string): T[] {
  return [...rows].sort((a, b) => compareNatural(key(a), key(b)));
}
