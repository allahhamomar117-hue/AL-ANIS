/**
 * الجلسة المحتسَبة يوم دوام — مصدر واحد لا شرط مكرّر.
 *
 * ── العلّة ───────────────────────────────────────────────────────────
 * صفّ attendance_sessions يُنشأ عند أول حفظ، ويبقى بعد حذف قيوده كلّها:
 * مشرف يفتح جلسة بالخطأ ثم يحذف طلابها واحداً واحداً يترك هيكلاً فارغاً.
 * والهيكل الفارغ كان يُحسب «يوم دوام» في كل تجميعة تعدّ الجلسات أو
 * الأيام المميّزة — فينخفض متوسط الحضور بيومٍ لم يقع أصلاً، ويظهر في
 * محور المخطّط اليومي عمودٌ لا شيء وراءه.
 *
 * ── لماذا شرطٌ في الاستعلام لا حذفٌ للصفوف ──────────────────────────
 * الحذف الجماعي عند الإقلاع يمسّ بيانات الإنتاج بلا مراجعة، وجلسةٌ
 * فارغة اليوم قد تكون جلسةً يُكمل تسجيلها غداً. والشرط يجعل الحساب
 * صحيحاً فوراً دون أن يُتلف شيئاً، ويبقى الحذف الصريح بيد المستخدم
 * (DELETE /api/attendance/sessions/:id).
 *
 * ── القاعدة ─────────────────────────────────────────────────────────
 * يوم دوام = جلسةٌ فيها قيد حضور واحد على الأقل، أياً كانت حالته:
 * الغائب حضورُه مسجَّل أيضاً — الجلسة التي كل طلابها غياب يومُ دوامٍ
 * وقع ولم يحضره أحد، وهي واقعة تُقاس لا تُخفى.
 *
 * ولذلك لا يُكتب الشرط في أي مسار: كل استعلام يستدعي هذه الدالة فيبقى
 * التعريف في ملف واحد — وأيّ تعديل عليه يسري على الجميع دفعةً واحدة.
 *
 * ملاحظة: هذا حارس «هل وقع الدوام؟» لا حارس صلاحيات؛ نطاق الرؤية في
 * services/scope.ts، والاستعلام التشغيلي يحتاج الاثنين معاً.
 */

/**
 * شرط الجلسة غير الفارغة.
 *
 * @param alias اسم جدول attendance_sessions في الاستعلام.
 *
 * مثال: `FROM attendance_sessions a WHERE ${countedSession("a")}`
 */
export function countedSession(alias = "a"): string {
  return `EXISTS (SELECT 1 FROM attendance_entries ae WHERE ae.session_id = ${alias}.id)`;
}
