/**
 * رؤية الطالب في الشاشات التشغيلية — مصدر واحد لا شرط مكرّر.
 *
 * للطالب علَمان مستقلّان عمداً:
 *   is_active  : سجلٌّ معطَّل — حُذف لخطأ في الإدخال (DELETE بلا hard).
 *   status     : طور الطالب — 'active' جارٍ، أو 'archived' انتهت دورته.
 *
 * الفرق ليس ترفاً: استرجاع دورةٍ مؤرشفة يجب ألّا يُعيد معه طالباً حُذف
 * خطأً، وإحصاء «كم طالباً تخرّج» غير إحصاء «كم سجلاً أُلغي».
 *
 * لكن علَمين على نفس السلوك (الإخفاء من الشاشات) بابٌ للانحراف: يكفي أن
 * ينسى استعلامٌ واحد أحدَهما ليظهر طالب مؤرشف في كشف الحضور. ولذلك لا
 * يُكتب الشرط في أي مسار: كل استعلام يستدعي visibleStudent() فيبقى
 * التعريف في ملف واحد — وأيّ تعديل عليه يسري على الجميع دفعةً واحدة.
 *
 * ملاحظة: هذا حارس «طور الطالب» لا حارس الصلاحيات. نطاق الرؤية حسب الدور
 * في services/scope.ts، والاستعلام التشغيلي يحتاج الاثنين معاً.
 */

export const STUDENT_STATUSES = ["active", "archived"] as const;
export type StudentStatus = (typeof STUDENT_STATUSES)[number];

/**
 * شرط الطالب الظاهر في الشاشات التشغيلية (تسميع، حضور، تقارير، ترشيح).
 *
 * @param alias اسم الجدول في الاستعلام، أو "" حين يُكتب بلا اسم
 *              (مثل `FROM students WHERE …`).
 *
 * مثال: `WHERE s.halaqa_id = ? AND ${visibleStudent("s")}`
 */
export function visibleStudent(alias = "s"): string {
  const p = alias ? `${alias}.` : "";
  return `${p}is_active = TRUE AND ${p}status = 'active'`;
}

/**
 * شرط الطالب القائم بصرف النظر عن طوره — المؤرشف داخلٌ فيه.
 *
 * لقوائم الإدارة وحدها (صفحة «كل الطلاب» بفلتر «الكل»). لا تستعمله في
 * شاشة تشغيلية: المؤرشف ليس له حضور ولا تسميع.
 */
export function existingStudent(alias = "s"): string {
  return `${alias ? `${alias}.` : ""}is_active = TRUE`;
}
